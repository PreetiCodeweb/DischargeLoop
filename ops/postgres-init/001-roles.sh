#!/bin/sh
set -eu

echo "Creating database roles..."

psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${APP_DB_USER}') THEN
    CREATE ROLE "${APP_DB_USER}" LOGIN PASSWORD '${APP_DB_PASSWORD}'
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  END IF;
END
\$\$;

DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${MIGRATION_DB_USER}') THEN
    CREATE ROLE "${MIGRATION_DB_USER}" LOGIN PASSWORD '${MIGRATION_DB_PASSWORD}'
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  END IF;
END
\$\$;

GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO "${APP_DB_USER}", "${MIGRATION_DB_USER}";

DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.schemata WHERE schema_name = 'dischargeloop') THEN
    CREATE SCHEMA dischargeloop AUTHORIZATION "${MIGRATION_DB_USER}";
  END IF;
END
\$\$;

GRANT USAGE ON SCHEMA dischargeloop TO "${APP_DB_USER}";

ALTER DEFAULT PRIVILEGES FOR ROLE "${MIGRATION_DB_USER}" IN SCHEMA dischargeloop
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "${APP_DB_USER}";

ALTER DEFAULT PRIVILEGES FOR ROLE "${MIGRATION_DB_USER}" IN SCHEMA dischargeloop
  GRANT USAGE, SELECT ON SEQUENCES TO "${APP_DB_USER}";

SQL

echo "Database roles created successfully."
